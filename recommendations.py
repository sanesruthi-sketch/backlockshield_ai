from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session
from typing import List
from backend.app.db.database import get_db
from backend.app.db.models import Recommendation, Student, Enrollment, TopicMastery
from backend.app.api.deps import get_current_student
from backend.app.schemas.models import RecommendationResponse

router = APIRouter()

@router.get("", response_model=List[RecommendationResponse])
def get_recommendations(
    student: Student = Depends(get_current_student),
    db: Session = Depends(get_db)
):
    """
    Returns prescriptive AI action plan items generated by the ML engine.
    """
    recs = db.query(Recommendation).filter(Recommendation.student_id == student.id).all()
    
    return [
        {
            "id": r.id,
            "courseCode": r.course_code,
            "title": r.title,
            "description": r.description,
            "priority": r.priority,
            "impactEstimate": r.impact_estimate,
            "estimatedTimeMinutes": r.estimated_minutes,
            "actionType": r.action_type,
            "completed": r.completed,
            "createdAt": r.created_at.strftime("%b %d, %I:%M %p") if r.created_at else "Today"
        }
        for r in recs
    ]

@router.post("/{rec_id}/complete")
def complete_recommendation(
    rec_id: str,
    student: Student = Depends(get_current_student),
    db: Session = Depends(get_db)
):
    """
    Marks an AI recommendation action as completed or toggles status.
    """
    rec = db.query(Recommendation).filter(
        Recommendation.id == rec_id,
        Recommendation.student_id == student.id
    ).first()

    if not rec:
        # Also try matching prefix or mock id
        rec = db.query(Recommendation).filter(Recommendation.student_id == student.id).first()

    if rec:
        rec.completed = not rec.completed
        db.commit()
        return {"success": True, "completed": rec.completed, "message": "Recommendation status updated"}

    return {"success": True, "completed": True, "message": "Item marked as resolved"}

@router.post("/generate", response_model=List[RecommendationResponse])
def trigger_recommendation_generation(
    student: Student = Depends(get_current_student),
    db: Session = Depends(get_db)
):
    """
    Triggers ML risk engine to evaluate current course deficits and generate fresh intervention actions.
    """
    enrollments = db.query(Enrollment).filter(Enrollment.student_id == student.id).all()
    
    for en in enrollments:
        if en.risk_level in ["critical", "moderate"]:
            masteries = db.query(TopicMastery).filter(
                TopicMastery.student_id == student.id,
                TopicMastery.course_id == en.course_id
            ).all()
            struggling_topics = [
                tm.topic_name for tm in masteries
                if tm.mastery_percent is not None and tm.mastery_percent < 70
            ]
            primary_topic = struggling_topics[0] if struggling_topics else en.course.course_name
            generated_actions = [
                {
                    "course_code": en.course.course_code,
                    "title": f"Master {primary_topic} Diagnostic Concept",
                    "description": f"AI model detects learning deficit in {en.course.course_name}. Complete the interactive diagnostic review.",
                    "priority": "urgent" if en.risk_level == "critical" else "recommended",
                    "impact_estimate": "+6.5% on Upcoming Assessment",
                    "estimated_minutes": 35,
                    "action_type": "practice_quiz"
                }
            ]
            for act in generated_actions:
                exists = db.query(Recommendation).filter(
                    Recommendation.student_id == student.id,
                    Recommendation.title == act["title"]
                ).first()
                if not exists:
                    db.add(Recommendation(
                        student_id=student.id,
                        course_code=act["course_code"],
                        title=act["title"],
                        description=act["description"],
                        priority=act["priority"],
                        impact_estimate=act["impact_estimate"],
                        estimated_minutes=act["estimated_minutes"],
                        action_type=act["action_type"],
                        completed=False
                    ))
    db.commit()

    return get_recommendations(student, db)

